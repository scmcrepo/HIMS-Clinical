-- ---------------------------------------------------------------------------
--  V217 — Tamil and Hindi consent notices  (WO-023, card E-005)
--
--  WHY THIS EXISTS
--
--  V211 seeded the seven notices in English only. This is a Tamil Nadu
--  deployment. A notice is only a notice if the person can read it — s. 5(3)
--  gives the data principal the right to the notice in any language in the
--  Eighth Schedule, and consent recorded against text the patient could not read
--  is not informed consent, whatever the consent_records table says.
--
--  ── READ THIS BEFORE SETTING notice_state = 'ACTIVE' ───────────────────────
--
--  These translations have NOT been reviewed by a qualified translator or by
--  counsel. They are seeded as DRAFT for exactly that reason, and they must not
--  be promoted to ACTIVE on the strength of this migration alone.
--
--  A wrong translation is worse than no translation. An English notice a patient
--  cannot read is obviously inadequate and everyone can see it. A fluent Tamil
--  notice that misstates who receives the data, or how long it is kept, is
--  inadequate in a way nobody can see — and the patient relies on it. The whole
--  point of the exercise is undone if the text is wrong.
--
--  Two sign-offs are needed before ACTIVE, and they are different jobs:
--    1. A qualified medical translator, for accuracy and register. These are
--       written for a patient at a reception desk, not for a lawyer.
--    2. Counsel, for the same reason the English version still says DRAFT.
--
--  ── The placeholders are still placeholders ────────────────────────────────
--
--  [HOSPITAL], [RETENTION] and [CONTACT] are carried through untranslated and
--  unresolved, exactly as in the English. Substituting a plausible retention
--  period here would be inventing a legal determination the hospital has not
--  made. The English notices carry the same gap and it is tracked as L-005.
--
--  ── Scope ──────────────────────────────────────────────────────────────────
--
--  Same version ('v2.0-draft') as the English, because these are the same notice
--  in another language rather than a new revision. The unique index on
--  (tenant_id, purpose, version, language) keeps them distinct, and the
--  ON CONFLICT makes this re-runnable.
--
--  Hindi is included because the patient population is not only Tamil-speaking;
--  the Eighth Schedule is not satisfied by adding one language and stopping.
--
--  Additive and idempotent. No data is read, written or destroyed.
-- ---------------------------------------------------------------------------

